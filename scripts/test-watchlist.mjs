assert.equal(WATCHLIST_LIMIT,50);
assert.deepEqual(parseTickerInput(' $dvlt, AAPL, dvlt, brk.b, , MSFT\nTSLA'),['DVLT','AAPL','BRK.B','MSFT','TSLA']);
